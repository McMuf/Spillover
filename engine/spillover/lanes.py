"""Challenges and replications: how disagreement becomes a structured, reviewed contribution.

* A **challenge** (``challenges/chl_*.yaml``) argues that a *registered* claim is wrong, names which
  aspect is at fault, and lists evidence. It is an argument, not a computation.
* A **replication** (``replications/rep_*.yaml``) is a *config*: the claim with a few named changes
  (another instrument, window, baseline, factor or measure). The engine runs it and generates the
  result under ``replications/results/``; people never write results by hand.

Both are append-only (submit a new one, never edit an old one) and are stamped with ``submitted_at``
by CI when they merge, exactly like claims are stamped with ``registered_at``.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import Annotated, Any, Literal, Self

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator, model_validator

from spillover.models import Claim, ClaimError, Instrument

PLACEHOLDER = "set_by_ci_on_merge"
_ID_TAIL = r"[a-z0-9]+(?:_[a-z0-9]+)*_v[0-9]+$"
CLAIM_ID = r"^clm_" + _ID_TAIL
_BAD_WORDS = ("REPLACE_ME", "YOUR_GITHUB_HANDLE")


class LaneError(ClaimError):
    """A challenge or replication file cannot be read or fails validation."""


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


def _clean(value: str) -> str:
    if any(w in value for w in _BAD_WORDS):
        raise ValueError("replace the template placeholder with real content")
    return value


class Evidence(_Strict):
    kind: Literal["link", "replication", "placebo", "data"]
    # A URL for links and data, or a replication id (rep_...) for replications and placebos.
    ref: Annotated[str, Field(min_length=3, max_length=300)]
    note: Annotated[str, Field(max_length=300)] = ""

    @model_validator(mode="after")
    def _ref_shape(self) -> Self:
        if self.kind in ("link", "data") and not self.ref.startswith("https://"):
            raise ValueError(f"evidence of kind '{self.kind}' needs an https:// link")
        if self.kind in ("replication", "placebo") and not re.match(r"^rep_" + _ID_TAIL, self.ref):
            raise ValueError(
                f"evidence of kind '{self.kind}' must name a replication id (rep_..._v1)"
            )
        return self


class Challenge(_Strict):
    id: Annotated[str, Field(pattern=r"^chl_" + _ID_TAIL)]
    claim: Annotated[str, Field(pattern=CLAIM_ID)]
    aspect: Literal["definition", "baseline", "sample", "data", "timing", "other"]
    argument: Annotated[str, Field(min_length=40, max_length=4000)]
    evidence: Annotated[list[Evidence], Field(max_length=10)] = Field(
        default_factory=lambda: list[Evidence]()
    )
    submitted_by: Annotated[str, Field(min_length=1, max_length=39)]
    submitted_at: Literal["set_by_ci_on_merge"] | datetime

    @field_validator("argument", "submitted_by")
    @classmethod
    def _no_placeholder(cls, v: str) -> str:
        return _clean(v)


class Changes(_Strict):
    """The only things a replication may change. The event type and triggers define the claim."""

    instrument: Instrument | None = None
    window_end: Annotated[str | None, Field(pattern=r"^\+[1-9][0-9]*_trading_days?$")] = None
    baseline: Literal["factor_only", "constant_mean"] | None = None
    factor: Annotated[str | None, Field(min_length=1)] = None
    factors: Annotated[list[str] | None, Field(min_length=1, max_length=3)] = None
    measure: Literal["abnormal_return", "abs_excess_return"] | None = None

    @model_validator(mode="after")
    def _something_changes(self) -> Self:
        if all(v is None for v in self.model_dump().values()):
            raise ValueError("a replication must change at least one thing")
        if self.factor is not None and self.factors is not None:
            raise ValueError("change either factor or factors, not both")
        return self


class Replication(_Strict):
    id: Annotated[str, Field(pattern=r"^rep_" + _ID_TAIL)]
    claim: Annotated[str, Field(pattern=CLAIM_ID)]
    changes: Changes
    rationale: Annotated[str, Field(min_length=20, max_length=1000)]
    submitted_by: Annotated[str, Field(min_length=1, max_length=39)]
    submitted_at: Literal["set_by_ci_on_merge"] | datetime

    @field_validator("rationale", "submitted_by")
    @classmethod
    def _no_placeholder(cls, v: str) -> str:
        return _clean(v)


class ReplicationResult(BaseModel):
    """Generated by ``spillover replicate``. Never written by hand; hashed like ledger records."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal[1] = 1
    replication_id: str
    claim_id: str
    applied_changes: dict[str, str]
    n_matched: int
    n_effective: int
    min_events: int
    mean: float | None
    ci_lo: float | None
    ci_hi: float | None
    p_value: float
    verdict: str
    as_of: str
    data_synthetic: bool
    engine_version: str
    rules_version: str
    sha256: Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]


def _parse[M: BaseModel](model: type[M], text: str, label: str) -> M:
    try:
        raw: Any = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise LaneError(f"{label}: cannot read file: {exc}") from exc
    if not isinstance(raw, dict):
        raise LaneError(f"{label}: must be a YAML mapping")
    try:
        return model.model_validate(raw)
    except ValidationError as exc:
        lines = [f"{label}: invalid {model.__name__.lower()}"]
        for err in exc.errors():
            where = ".".join(str(p) for p in err["loc"]) or "<root>"
            lines.append(f"  - {where}: {err['msg']}")
        raise LaneError("\n".join(lines)) from exc


def parse_challenge(text: str, label: str) -> Challenge:
    return _parse(Challenge, text, label)


def parse_replication(text: str, label: str) -> Replication:
    return _parse(Replication, text, label)


def lane_files(directory: Path) -> list[Path]:
    """Submissions in a directory; files starting with ``_`` (the templates) are skipped."""
    return sorted(p for p in directory.glob("*.yaml") if not p.name.startswith("_"))


def load_challenge(path: Path) -> Challenge:
    return parse_challenge(_read(path), str(path))


def load_replication(path: Path) -> Replication:
    return parse_replication(_read(path), str(path))


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise LaneError(f"{path}: cannot read file: {exc}") from exc


def check_target(claim: Claim | None, claim_id: str) -> str | None:
    """Why this claim cannot be challenged or replicated, or None if it can.

    Disagreement belongs in the challenge lane *after* a claim is registered; before that, the
    claim is still under review in its own pull request.
    """
    if claim is None:
        return f"claim {claim_id} does not exist in claims/"
    if claim.registered_at_utc is None:
        return f"claim {claim_id} is not registered yet; comment on its pull request instead"
    return None


def apply_changes(claim: Claim, changes: Changes) -> Claim:
    """The claim with a replication's changes applied (validated again by the claim model)."""
    data = claim.model_dump(mode="python")
    if changes.instrument is not None:
        data["instrument"] = changes.instrument.model_dump()
    if changes.window_end is not None:
        data["window"] = {"start": "first_report", "end": changes.window_end}
    for field in ("baseline", "measure"):
        value = getattr(changes, field)
        if value is not None:
            data[field] = value
    # One factor or several: setting one form clears the other, so the result is unambiguous.
    if changes.factor is not None:
        data["factor"], data["factors"] = changes.factor, None
    if changes.factors is not None:
        data["factors"] = list(changes.factors)
        data.pop("factor", None)
    try:
        return Claim.model_validate(data)
    except ValidationError as exc:
        raise LaneError(f"the changes do not make a valid claim: {exc.errors()[0]['msg']}") from exc


def describe_changes(changes: Changes) -> dict[str, str]:
    out: dict[str, str] = {}
    if changes.instrument is not None:
        out["instrument"] = f"{changes.instrument.symbol} ({changes.instrument.venue})"
    for field in ("window_end", "baseline", "factor", "measure"):
        value = getattr(changes, field)
        if value is not None:
            out[field] = str(value)
    if changes.factors is not None:
        out["factors"] = "+".join(changes.factors)
    return out

import type { ChallengeOut, ReplicationOut } from "../generated/site";
import { intervalText, pct } from "../lib/format";

const ASPECT: Record<ChallengeOut["aspect"], string> = {
  definition: "the claim's definition",
  baseline: "the baseline",
  sample: "the sample",
  data: "the data",
  timing: "the timing",
  other: "something else",
};

function when(stamp: string | null): string {
  return stamp ? stamp.slice(0, 10) : "awaiting registration";
}

export function ChallengeList({ items }: { items: ChallengeOut[] }) {
  return (
    <ul className="space-y-3">
      {items.map((c) => (
        <li key={c.id}>
          <article className="rounded-xl border border-line bg-surface p-4">
            <header className="mb-2 flex flex-wrap items-baseline gap-x-3 gap-y-1">
              <span className="font-mono text-xs text-muted">{c.id}</span>
              <span className="text-xs font-semibold uppercase tracking-wide">Challenges {ASPECT[c.aspect]}</span>
              <span className="text-xs text-muted">
                by {c.submitted_by} · {when(c.submitted_at)}
              </span>
            </header>
            <p className="whitespace-pre-wrap text-sm">{c.argument}</p>
            {c.evidence.length > 0 && (
              <ul className="mt-3 space-y-1 text-sm">
                {c.evidence.map((e) => (
                  <li key={`${e.kind}:${e.ref}`}>
                    <span className="text-xs uppercase tracking-wide text-muted">{e.kind}</span>{" "}
                    {e.kind === "link" || e.kind === "data" ? (
                      <a className="break-all underline" href={e.ref} rel="noopener noreferrer">
                        {e.ref}
                      </a>
                    ) : (
                      <span className="font-mono text-xs">{e.ref}</span>
                    )}
                    {e.note && <span className="text-muted"> · {e.note}</span>}
                  </li>
                ))}
              </ul>
            )}
          </article>
        </li>
      ))}
    </ul>
  );
}

export function ReplicationList({ items }: { items: ReplicationOut[] }) {
  return (
    <ul className="space-y-3">
      {items.map((r) => (
        <li key={r.id}>
          <article className="rounded-xl border border-line bg-surface p-4">
            <header className="mb-2 flex flex-wrap items-baseline gap-x-3 gap-y-1">
              <span className="font-mono text-xs text-muted">{r.id}</span>
              <span className="text-xs text-muted">
                by {r.submitted_by} · {when(r.submitted_at)}
              </span>
            </header>
            <p className="text-sm">{r.rationale}</p>
            <dl className="mt-3 grid gap-x-6 gap-y-1 text-sm sm:grid-cols-2">
              {Object.entries(r.changes).map(([k, v]) => (
                <div key={k} className="flex gap-2">
                  <dt className="text-muted">{k.replace(/_/g, " ")}</dt>
                  <dd className="font-mono text-xs">{v}</dd>
                </div>
              ))}
            </dl>
            <div className="mt-3 rounded-xl bg-surface-alt p-3 text-sm">
              {r.result ? (
                <>
                  <p>
                    <span className="text-xs font-semibold uppercase tracking-wide">Backtest result</span> · generated by
                    the engine, not written by hand
                    {r.result.data_synthetic && " · on SYNTHETIC data"}
                  </p>
                  <p className="mt-1">
                    {pct(r.result.mean)} <span className="text-muted">{intervalText(r.result.ci_lo, r.result.ci_hi)}</span>{" "}
                    · n={r.result.n_effective} of {r.result.n_matched} matched · as of {r.result.as_of}
                  </p>
                  <p className="mt-1 text-muted">{r.result.verdict}</p>
                </>
              ) : (
                <p className="text-muted">No result yet. The engine runs a replication after it merges.</p>
              )}
            </div>
          </article>
        </li>
      ))}
    </ul>
  );
}
